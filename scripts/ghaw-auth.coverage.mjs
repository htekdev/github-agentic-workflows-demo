// Native V8 coverage for workflow tooling; application/regression tests stay in Vitest.
import test from 'node:test';
import assert from 'node:assert/strict';
import { authViolations } from './ghaw-auth.mjs';

test('all authentication contract acceptance and rejection paths', () => {
  const source = 'copilot-requests: write\n';
  const lock = `# generated by gh-aw (v1.2.2)
copilot-requests: write
COPILOT_GITHUB_TOKEN: \${{ github.token }}
S2STOKENS: true
uses: github/gh-aw-actions/setup@53d0749e19424a918acd82b4d140264ce48f2f14
`;
  assert.deepEqual(authViolations(source, lock), []);
  const failures = [
    ['sourcePermission', '', lock],
    ['compiledPermission', source, lock.replace('copilot-requests: write', '')],
    ['ephemeralCredential', source, lock.replace('github.token', 'secrets.OTHER')],
    ['exchangeEnabled', source, lock.replace('S2STOKENS: true', '')],
    ['exchangeEnabled', source, lock + 'S2STOKENS: true\n'],
    ['noStoredCopilotSecret', source + 'secrets.COPILOT_GITHUB_TOKEN', lock],
    ['noStoredCopilotSecret', source, lock + `secrets['COPILOT_GITHUB_TOKEN']`],
    ['noBlanketWrite', source + 'write-all', lock],
    ['pinnedRuntime', source, lock.replace('53d0749e19424a918acd82b4d140264ce48f2f14', 'main')],
    ['compatibleCompiler', source, lock.replace('v1.2.2', 'v0.45.2')],
    ['fetchCompatibility', source + 'tools:\n  web-fetch:\n', lock],
  ];
  for (const [failure, input, compiled] of failures) {
    assert.ok(authViolations(input, compiled).includes(failure), failure);
  }
  assert.deepEqual(authViolations(source + 'tools:\n  web-fetch:\nengine:\n  copilot-sdk: true\n', lock), []);
});
